use std::time::{SystemTime, UNIX_EPOCH};

use wakode_core::Micros;

/// Текущее время в микросекундах от эпохи UTC.
///
/// Единственный источник времени **для колонок**: `received_at`,
/// `created_at`, `marked_at` и отметки об использовании ключа берутся
/// отсюда по одному разу на операцию, иначе в пределах одной транзакции
/// появились бы расходящиеся значения «сейчас».
///
/// Единственным местом в крейте, где читаются системные часы, этот модуль
/// **не является**: `Uuid::now_v7()` тоже читает `SystemTime::now()`, и
/// зовётся он в `users.rs`, `keys.rs`, `sessions.rs` и `heartbeats.rs` —
/// последний внутри цикла по батчу, то есть на батч в 20 000 отметок
/// приходится 20 000 независимых чтений часов. Метка внутри
/// v7-идентификатора поэтому расходится с `received_at`, взятым один раз на
/// весь батч, — ровно то расхождение, ради устранения которого модуль и
/// заведён. Перевод генерации UUID на этот источник — отдельное решение, не
/// сделанное в волне 0.
pub(crate) fn now() -> Micros {
    let since_epoch = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default();
    Micros::new(since_epoch.as_micros() as i64)
}
