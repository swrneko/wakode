// # Как в этом крейте обращаются с секретами
//
// Правило одно на все модули, и оно асимметрично намеренно.
//
// **`Debug` не печатает секрет никогда.** Это форматирование по умолчанию
// у `tracing`, `#[instrument]`, `unwrap`, `expect` и производного `Debug`
// любой структуры, которая секрет содержит. Утечка здесь случается сама
// собой, без чьего-либо решения, и стоит одной строки в чужом коде.
// Каждый такой тип реализует `Debug` вручную и подпирается тестом со
// сверкой точной строки — поиск подстроки в этом крейте трижды оказывался
// зелёным на утёкшем секрете.
//
// **`Display` печатает секрет дословно — там, где он есть.** Он есть у
// `ApiKeyValue` и `SessionToken`, потому что эти значения обязаны уехать
// наружу: первое пользователь копирует в редактор, второе — в cookie. Тем
// же путём идёт `SetupToken` — его `Display` печатает бинарь `wakode` в
// журнал при старте, и это единственное место в проекте, где секрет
// пишется в лог намеренно: владельцу за обратным прокси токен взять больше
// неоткуда. `Display` вызывают, только написав `{}` осознанно.
//
// `MasterKey` `Display` не имеет вовсе: наружу он не уезжает никогда, и
// достать его можно лишь явным `to_base64()`. Отсутствие — не забывчивость.
//
// Отсюда практическое следствие для вызывающих: `tracing::info!("{token}")`
// отдаёт токен в лог, а `tracing::info!("{token:?}")` — нет. Логировать
// значения этих типов не надо ни в каком виде; если нужен идентификатор
// сессии или ключа для отладки — бери `id` соответствующей строки базы,
// он для того и есть.
